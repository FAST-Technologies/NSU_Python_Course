"""for loops with range()."""

print("0 to 4:")
for number in range(5):
    print(number)

print("2 to 7:")
for number in range(2, 8):
    print(number)

print("Even numbers from 2 to 10:")
for number in range(2, 11, 2):
    print(number)

print("Countdown:")
for number in range(5, 0, -1):
    print(number)
