"""
Examples of basic Python data types.
"""



# Integer
student_count = 25

# Floating-point number
temperature = 21.5

# String
course_name = "Python"

# Boolean
course_started = True


print("Values:")
print(student_count)
print(temperature)
print(course_name)
print(course_started)


print()

print("Types:")
print(type(student_count))
print(type(temperature))
print(type(course_name))
print(type(course_started))


print()

print("Arithmetic example:")

a = 17
b = 5

print("a =", a)
print("b =", b)

print("a + b =", a + b)
print("a - b =", a - b)
print("a * b =", a * b)
print("a / b =", a / b)
print("a // b =", a // b)
print("a % b =", a % b)
print("a ** b =", a ** b)